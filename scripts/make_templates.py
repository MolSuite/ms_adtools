"""Writes src/ms_adtools/templates.py: the cofactors' CCD components as SMILES at pH 7.

    python scripts/make_templates.py            # fetches the components into the CCD cache

Each component is read from the CCD, its acids ionized (phosphate, carboxylic, sulfonic) and its
aliphatic amines protonated, then written as SMILES with its heavy-atom names in SMILES order,
which is how ccd._apply matches a residue to it. Add a code to CODES and run again.
"""
import sys
from pathlib import Path

import gemmi
from rdkit import Chem

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from ms_adtools.ccd import _ACID_H, component_file, template  # noqa: E402

CODES = "ADP AMP ATP COA FAD FMN HEM NAD NAP PQQ SAH SAM TPP".split()
# a neutral N whose neighbours are all sp3 carbons (SAM's and SAH's alpha-amine)
_AMINE = Chem.MolFromSmarts("[NX3;+0;!$(N~[!#6;!#1]);!$(N-[#6;!X4])]")
OUT = Path(__file__).resolve().parents[1] / "src" / "ms_adtools" / "templates.py"


def at_ph7(code):
    path = component_file(code)
    if path is None:
        raise SystemExit(f"{code}: no CCD component (offline?)")
    mol, names, metals = template(gemmi.cif.read(str(path)).sole_block())
    rw = Chem.RWMol(mol)
    for i in mol.GetSubstructMatches(_AMINE):
        n = rw.GetAtomWithIdx(i[0])
        n.SetFormalCharge(1)
        n.SetNumExplicitHs(n.GetNumExplicitHs() + 1)
    for h, o, _ in sorted(mol.GetSubstructMatches(_ACID_H), reverse=True):
        rw.GetAtomWithIdx(o).SetFormalCharge(-1)
        rw.RemoveAtom(h)
        del names[h]
    heavy = [n for n, a in zip(names, rw.GetAtoms()) if a.GetAtomicNum() > 1]
    mol = Chem.RemoveHs(rw.GetMol())  # heavy atoms keep their order
    smiles = Chem.MolToSmiles(mol)
    order = [heavy[i] for i in mol.GetPropsAsDict(True, True)["_smilesAtomOutputOrder"]]
    check = Chem.MolFromSmiles(smiles)
    assert [a.GetSymbol() for a in check.GetAtoms()] == [mol.GetAtomWithIdx(heavy.index(n)).GetSymbol() for n in order]
    return smiles, tuple(order), metals, Chem.GetFormalCharge(mol)


def main():
    rows = []
    for code in CODES:
        smiles, names, metals, charge = at_ph7(code)
        rows.append(f"    {code!r}: ({smiles!r},\n            {names!r},\n            {metals!r}),  # {charge:+d}")
        print(code, f"{charge:+d}", metals or "")
    OUT.write_text(
        '"""Cofactor templates at pH 7: {resname: (SMILES, heavy-atom names in SMILES order, {metal: charge})}.\n\n'
        "Generated by scripts/make_templates.py from the CCD; do not edit by hand. The comment is the\n"
        "net charge without the metal. Imports nothing, so a caller can read COFACTORS cheaply.\n"
        '"""\n'
        "TEMPLATES = {\n" + "\n".join(rows) + "\n}\n"
        "COFACTORS = frozenset(TEMPLATES)\n")


if __name__ == "__main__":
    main()
